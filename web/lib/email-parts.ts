// Места переноса адреса e-mail в таблицах «Людей и групп» (DESIGN §6.11):
// после «@» и точек — длинный адрес ломается по частям, а не посреди
// слова. Чистая функция — её проверяют тесты lib/email-parts.test.ts
// (npm test).

// emailParts — адрес кусками: каждый кончается «@» или точкой, кроме
// последнего; между кусками ставится <wbr>. Склеенные куски — снова адрес
export function emailParts(email: string): string[] {
  return email.match(/[^@.]+[@.]?|[@.]/g) ?? [email];
}
