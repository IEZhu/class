// UtteranceText — единственное место, где рендерится текст реплики
// транскрипта (S2-4). Любой текст платформы идёт через один <ClickableText>
// (S3-1); когда он появится, это тело заменится одной строкой, и слова
// станут кликабельными во всём транскрипте сразу (ADR-025).
export default function UtteranceText({ text }: { text: string }) {
  return <>{text}</>;
}
